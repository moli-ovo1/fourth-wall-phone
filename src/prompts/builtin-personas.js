export function getBuiltinPersonaPrompt(contactId) {
  return BUILTIN_PERSONA_PROMPTS[String(contactId || '')] || '';
}

export function getFourthWallCommentaryPrompt() {
  return FOURTH_WALL_COMMENTARY_PROTOCOL;
}

export function hasBuiltinPersonaPrompt(contactId) {
  return Boolean(getBuiltinPersonaPrompt(contactId));
}
